"""Schemas for Context Forge database workbench summaries."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class ContextForgeMapping(BaseModel):
    """A source object mapped into the future context graph."""

    object_name: str
    inferred_entity: str
    rows: int = 0
    columns: int = 0
    foreign_keys: int = 0
    pii: List[str] = Field(default_factory=list)
    selected: bool = True


class ContextForgeGraphSummary(BaseModel):
    """Graph commit summary for one source connection."""

    entity_count: int = 0
    graph_events_total: int = 0
    nodes_committed: int = 0
    edges_committed: int = 0
    neo4j_nodes: int = 0
    neo4j_edges: int = 0
    events_pending: int = 0
    events_failed: int = 0
    events_skipped: int = 0


class ContextForgeGraphPreviewNode(BaseModel):
    """Node rendered in the Forge graph-schema preview."""

    id: str
    label: str
    kind: str = "entity"
    source_object: Optional[str] = None
    status: str = "draft"
    confidence: float = 0.8
    x: float = 0
    y: float = 0
    metrics: Dict[str, Any] = Field(default_factory=dict)
    properties: List[str] = Field(default_factory=list)
    badges: List[str] = Field(default_factory=list)


class ContextForgeGraphPreviewEdge(BaseModel):
    """Edge rendered in the Forge graph-schema preview."""

    id: str
    source: str
    target: str
    label: str
    kind: str = "relationship"
    status: str = "draft"
    confidence: float = 0.8


class ContextForgeGraphPreview(BaseModel):
    """Compact graph-schema preview generated by Context Forge."""

    status: str = "draft"
    provider: Optional[str] = None
    source_name: Optional[str] = None
    generated_at: datetime
    nodes: List[ContextForgeGraphPreviewNode] = Field(default_factory=list)
    edges: List[ContextForgeGraphPreviewEdge] = Field(default_factory=list)
    summary: Dict[str, Any] = Field(default_factory=dict)
    warnings: List[str] = Field(default_factory=list)


class ContextForgeMappingArtifact(BaseModel):
    """Stored, editable Context Forge mapping artifact."""

    id: UUID
    source_connection_id: Optional[UUID] = None
    setup_draft_id: Optional[UUID] = None
    target_collection_id: Optional[str] = None
    provider_short_name: str
    source_name: str
    version: int
    status: str
    generated_by: str
    mapping_schema: Dict[str, Any]
    graph_preview: ContextForgeGraphPreview
    schema_fingerprint: Optional[Dict[str, Any]] = None
    drift_snapshot: Optional[Dict[str, Any]] = None
    applied_at: Optional[datetime] = None
    created_at: datetime
    modified_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ContextForgeMappingUpdate(BaseModel):
    """Editable mapping payload saved from Forge Studio."""

    mapping_schema: Optional[Dict[str, Any]] = None
    graph_preview: Optional[ContextForgeGraphPreview] = None
    status: Optional[str] = None


class ContextForgeSourceSummary(BaseModel):
    """Context Forge summary for a connected source."""

    source_connection_id: UUID
    source_name: str
    provider: str
    sync_id: Optional[UUID] = None
    status: str = "active"
    cursor_field: Optional[str] = None
    schedule: Optional[Dict[str, Any]] = None
    auth_summary: Optional[Dict[str, Any]] = None
    source_identity: Dict[str, Any] = Field(default_factory=dict)
    totals: Dict[str, Any] = Field(default_factory=dict)
    sync_estimate: Dict[str, Any] = Field(default_factory=dict)
    mappings: List[ContextForgeMapping] = Field(default_factory=list)
    graph: ContextForgeGraphSummary = Field(default_factory=ContextForgeGraphSummary)
    forge_ready: bool = False
    drift: Dict[str, Any] = Field(default_factory=dict)
    mapping_artifact: Optional[ContextForgeMappingArtifact] = None
    graph_preview: Optional[ContextForgeGraphPreview] = None


class ContextForgePipelineStep(BaseModel):
    """Workbench pipeline step derived from sync and graph state."""

    key: str
    label: str
    status: str
    detail: str


class ContextForgeDatabaseSummary(BaseModel):
    """Database-scoped Context Forge/workbench summary."""

    collection_id: UUID
    readable_id: str
    name: str
    generated_at: datetime
    totals: Dict[str, Any]
    pipeline: List[ContextForgePipelineStep]
    sources: List[ContextForgeSourceSummary]
