    async def get_database_summary(
        self,
        db: AsyncSession,
        *,
        readable_id: str,
        ctx: ApiContext,
    ) -> schemas.ContextForgeDatabaseSummary:
        """Return a database-scoped Context Forge summary."""
        collection = await crud.collection.get_by_readable_id(
            db, readable_id=readable_id, ctx=ctx
        )
        if not collection:
            raise HTTPException(status_code=404, detail="Context database not found")

        source_result = await db.execute(
            select(SourceConnection)
            .where(SourceConnection.organization_id == ctx.organization.id)
            .where(SourceConnection.readable_collection_id == collection.readable_id)
            .order_by(SourceConnection.created_at.desc())
        )
        source_connections = list(source_result.scalars().all())

        source_summaries = [
            await self._build_source_summary(db, source_connection, ctx)
            for source_connection in source_connections
        ]

        totals = {
            "sources": len(source_summaries),
            "entities": sum(source.graph.entity_count for source in source_summaries),
            "graph_events": sum(source.graph.graph_events_total for source in source_summaries),
            "nodes_committed": sum(source.graph.nodes_committed for source in source_summaries),
            "edges_committed": sum(source.graph.edges_committed for source in source_summaries),
            "neo4j_nodes": sum(source.graph.neo4j_nodes for source in source_summaries),
            "neo4j_edges": sum(source.graph.neo4j_edges for source in source_summaries),
            "pending_events": sum(source.graph.events_pending for source in source_summaries),
            "failed_events": sum(source.graph.events_failed for source in source_summaries),
            "forge_ready_sources": sum(1 for source in source_summaries if source.forge_ready),
        }

        return schemas.ContextForgeDatabaseSummary(
            collection_id=collection.id,
            readable_id=collection.readable_id,
            name=collection.name,
            generated_at=utc_now_naive(),
            totals=totals,
            pipeline=self._build_pipeline(totals),
            sources=source_summaries,
        )

    async def upsert_draft_mapping(
        self,
        db: AsyncSession,
        *,
        draft: SourceConnectionSetupDraft,
        discovery_snapshot: Mapping[str, Any],
        ctx: ApiContext,
    ) -> schemas.ContextForgeMappingArtifact:
        """Create or refresh the Forge draft generated by setup discovery."""
        source_name = draft.connection_name or f"{draft.provider_short_name}-connection"
        payload = self.build_mapping_artifact_payload(
            provider=draft.provider_short_name,
            source_name=source_name,
            target_collection_id=draft.target_collection_id,
            discovery_snapshot=discovery_snapshot,
            status="draft",
            generated_by="setup_discovery",
        )
        payload = await self._apply_ai_inference(
            payload,
            provider=draft.provider_short_name,
            source_name=source_name,
            target_collection_id=draft.target_collection_id,
            status="draft",
            ctx=ctx,
        )
        result = await db.execute(
            select(ContextForgeMappingArtifactModel)
            .where(ContextForgeMappingArtifactModel.organization_id == ctx.organization.id)
            .where(ContextForgeMappingArtifactModel.setup_draft_id == draft.id)
            .where(ContextForgeMappingArtifactModel.source_connection_id.is_(None))
            .order_by(ContextForgeMappingArtifactModel.version.desc())
            .limit(1)
        )
        artifact = result.scalar_one_or_none()
        if not artifact:
            artifact = ContextForgeMappingArtifactModel(
                organization_id=ctx.organization.id,
                setup_draft_id=draft.id,
                target_collection_id=draft.target_collection_id,
                provider_short_name=draft.provider_short_name,
                source_name=source_name,
                version=1,
                status="draft",
                generated_by="setup_discovery",
                mapping_schema=payload["mapping_schema"],
                graph_preview=payload["graph_preview"],
                schema_fingerprint=payload["schema_fingerprint"],
                drift_snapshot=None,
            )
            if ctx.has_user_context:
                artifact.created_by_email = ctx.tracking_email
                artifact.modified_by_email = ctx.tracking_email
            db.add(artifact)
            await db.flush()
        else:
            artifact.target_collection_id = draft.target_collection_id
            artifact.provider_short_name = draft.provider_short_name
            artifact.source_name = source_name
            artifact.status = "draft"
            artifact.generated_by = "setup_discovery"
            artifact.mapping_schema = payload["mapping_schema"]
            artifact.graph_preview = payload["graph_preview"]
            artifact.schema_fingerprint = payload["schema_fingerprint"]
            if ctx.has_user_context:
                artifact.modified_by_email = ctx.tracking_email
            await db.flush()

        return self._mapping_artifact_response(artifact)

    async def promote_draft_mapping_to_source(
        self,
        db: AsyncSession,
        *,
        draft: SourceConnectionSetupDraft | None = None,
        setup_draft_id: UUID | None = None,
        source_connection: SourceConnection,
        discovery_snapshot: Mapping[str, Any] | None,
        drift_snapshot: Mapping[str, Any] | None,
        ctx: ApiContext,
    ) -> schemas.ContextForgeMappingArtifact:
        """Attach the setup Forge draft to the finalized source connection."""
        if setup_draft_id is None:
            if draft is None:
                raise ValueError("setup_draft_id or draft is required")
            setup_draft_id = draft.id

        result = await db.execute(
            select(ContextForgeMappingArtifactModel)
            .where(ContextForgeMappingArtifactModel.organization_id == ctx.organization.id)
            .where(ContextForgeMappingArtifactModel.setup_draft_id == setup_draft_id)
            .order_by(ContextForgeMappingArtifactModel.version.desc())
            .limit(1)
        )
        artifact = result.scalar_one_or_none()
        if not artifact:
            payload = self.build_mapping_artifact_payload(
                provider=source_connection.short_name,
                source_name=source_connection.name,
                target_collection_id=source_connection.readable_collection_id,
                discovery_snapshot=discovery_snapshot or {},
                status="active",
                generated_by="setup_finalize",
                drift_snapshot=drift_snapshot,
            )
            payload = await self._apply_ai_inference(
                payload,
                provider=source_connection.short_name,
                source_name=source_connection.name,
                target_collection_id=source_connection.readable_collection_id,
                status="active",
                ctx=ctx,
            )
            artifact = ContextForgeMappingArtifactModel(
                organization_id=ctx.organization.id,
                setup_draft_id=setup_draft_id,
                source_connection_id=source_connection.id,
                target_collection_id=source_connection.readable_collection_id,
                provider_short_name=source_connection.short_name,
                source_name=source_connection.name,
                version=1,
                status="active",
                generated_by="setup_finalize",
                mapping_schema=payload["mapping_schema"],
                graph_preview=payload["graph_preview"],
                schema_fingerprint=payload["schema_fingerprint"],
                drift_snapshot=dict(drift_snapshot or {}),
                applied_at=utc_now_naive(),
            )
            db.add(artifact)
        else:
            artifact.source_connection_id = source_connection.id
            artifact.target_collection_id = source_connection.readable_collection_id
            artifact.provider_short_name = source_connection.short_name
            artifact.source_name = source_connection.name
            artifact.status = "active"
            artifact.generated_by = "setup_finalize"
            artifact.drift_snapshot = dict(drift_snapshot or {})
            artifact.applied_at = utc_now_naive()
            if discovery_snapshot:
                payload = self.build_mapping_artifact_payload(
                    provider=source_connection.short_name,
                    source_name=source_connection.name,
                    target_collection_id=source_connection.readable_collection_id,
                    discovery_snapshot=discovery_snapshot,
                    status="active",
                    generated_by="setup_finalize",
                    drift_snapshot=drift_snapshot,
                )
                payload = await self._apply_ai_inference(
                    payload,
                    provider=source_connection.short_name,
                    source_name=source_connection.name,
                    target_collection_id=source_connection.readable_collection_id,
                    status="active",
                    ctx=ctx,
                )
                artifact.mapping_schema = payload["mapping_schema"]
                artifact.graph_preview = payload["graph_preview"]
                artifact.schema_fingerprint = payload["schema_fingerprint"]
        if ctx.has_user_context:
            artifact.modified_by_email = ctx.tracking_email
        await db.flush()
        return self._mapping_artifact_response(artifact)

    async def mark_source_mapping_drift(
        self,
        db: AsyncSession,
        *,
        source_connection: SourceConnection,
        drift: Mapping[str, Any],
    ) -> None:
        """Mark the active Forge mapping as needing review when source shape drifts."""
        schema_changed = bool((drift.get("schema") or {}).get("changed"))
        config_changed = bool((drift.get("config") or {}).get("changed"))
        if not schema_changed and not config_changed:
            return

        artifact = await self._get_latest_source_mapping(
            db,
            source_connection_id=source_connection.id,
            organization_id=source_connection.organization_id,
        )
        if not artifact or artifact.status in {"review_required", "draft"}:
            return
        artifact.status = "review_required"
        artifact.generated_by = "drift"
        artifact.drift_snapshot = dict(drift)
        await db.flush()

    async def regenerate_source_mapping(
        self,
        db: AsyncSession,
        *,
        source_connection_id: UUID,
        ctx: ApiContext,
    ) -> schemas.ContextForgeMappingArtifact:
        """Generate a new editable mapping version from latest catalog/discovery."""
        source_connection = await crud.source_connection.get(
            db, id=source_connection_id, ctx=ctx
        )
        if not source_connection:
            raise HTTPException(status_code=404, detail="Source connection not found")

        draft = await self._get_finalized_draft(db, source_connection, ctx)
        catalog_snapshot = await self._get_catalog_snapshot(db, source_connection, ctx)
        discovery_snapshot = (
            self._discovery_from_catalog(catalog_snapshot, source_connection)
            if catalog_snapshot
            else (draft.discovery_snapshot if draft and draft.discovery_snapshot else {})
        )
        current = await self._get_latest_source_mapping(
            db,
            source_connection_id=source_connection.id,
            organization_id=ctx.organization.id,
        )
        next_version = int(current.version if current else 0) + 1
        payload = self.build_mapping_artifact_payload(
            provider=source_connection.short_name,
            source_name=source_connection.name,
            target_collection_id=source_connection.readable_collection_id,
            discovery_snapshot=discovery_snapshot,
            catalog_snapshot=catalog_snapshot,
            status="review_required",
            generated_by="manual_regenerate",
            drift_snapshot=(source_connection.config_fields or {}).get("drift"),
        )
        payload = await self._apply_ai_inference(
            payload,
            provider=source_connection.short_name,
            source_name=source_connection.name,
            target_collection_id=source_connection.readable_collection_id,
            status="review_required",
            ctx=ctx,
        )
        artifact = ContextForgeMappingArtifactModel(
            organization_id=ctx.organization.id,
            source_connection_id=source_connection.id,
            setup_draft_id=draft.id if draft else None,
            target_collection_id=source_connection.readable_collection_id,
            provider_short_name=source_connection.short_name,
            source_name=source_connection.name,
            version=next_version,
            status="review_required",
            generated_by="manual_regenerate",
            mapping_schema=payload["mapping_schema"],
            graph_preview=payload["graph_preview"],
            schema_fingerprint=payload["schema_fingerprint"],
            drift_snapshot=(source_connection.config_fields or {}).get("drift") or {},
        )
        if ctx.has_user_context:
            artifact.created_by_email = ctx.tracking_email
            artifact.modified_by_email = ctx.tracking_email
        db.add(artifact)
        await db.flush()
        return self._mapping_artifact_response(artifact)

    async def update_mapping(
        self,
        db: AsyncSession,
        *,
        mapping_id: UUID,
        update_in: schemas.ContextForgeMappingUpdate,
        ctx: ApiContext,
    ) -> schemas.ContextForgeMappingArtifact:
        artifact = await self._get_mapping_or_404(db, mapping_id=mapping_id, ctx=ctx)
        if update_in.mapping_schema is not None:
            mapping_schema = deepcopy(update_in.mapping_schema)
            artifact.mapping_schema = mapping_schema
            artifact.graph_preview = (
                update_in.graph_preview.model_dump(mode="json")
                if update_in.graph_preview
                else self._graph_preview_from_mapping_schema(
                    mapping_schema=mapping_schema,
                    provider=artifact.provider_short_name,
                    source_name=artifact.source_name,
                    status=update_in.status or "draft",
                )
            )
        elif update_in.graph_preview is not None:
            artifact.graph_preview = update_in.graph_preview.model_dump(mode="json")
        if update_in.status:
            artifact.status = update_in.status
        elif artifact.status == "active":
            artifact.status = "draft"
        artifact.generated_by = "manual_edit"
        if ctx.has_user_context:
            artifact.modified_by_email = ctx.tracking_email
        await db.flush()
        return self._mapping_artifact_response(artifact)

    async def apply_mapping(
        self,
        db: AsyncSession,
        *,
        mapping_id: UUID,
        ctx: ApiContext,
    ) -> schemas.ContextForgeMappingArtifact:
        artifact = await self._get_mapping_or_404(db, mapping_id=mapping_id, ctx=ctx)
        if not artifact.source_connection_id:
            raise HTTPException(
                status_code=400,
                detail="Only finalized source mappings can be applied",
            )
        await db.execute(
            update(ContextForgeMappingArtifactModel)
            .where(ContextForgeMappingArtifactModel.organization_id == ctx.organization.id)
            .where(ContextForgeMappingArtifactModel.source_connection_id == artifact.source_connection_id)
            .where(ContextForgeMappingArtifactModel.id != artifact.id)
            .where(ContextForgeMappingArtifactModel.status == "active")
            .values(status="archived")
        )
        source_connection = await crud.source_connection.get(
            db,
            id=artifact.source_connection_id,
            ctx=ctx,
        )
        if source_connection:
            from contextd.core.source_drift_service import source_drift_service

            artifact.drift_snapshot = await source_drift_service.accept_current_baseline(
                db=db,
                source_connection=source_connection,
                ctx=ctx,
            )
        artifact.status = "active"
        artifact.generated_by = "manual_apply"
        artifact.applied_at = utc_now_naive()
        if ctx.has_user_context:
            artifact.modified_by_email = ctx.tracking_email
        await db.flush()
        return self._mapping_artifact_response(artifact)

    async def _get_latest_job_entity_count(
        self,
        db: AsyncSession,
        *,
        sync_id: UUID,
    ) -> int:
        """Return the latest non-zero completed entity observation for a sync.

        Forge summaries are operational read models. If EntityCount rows are not
        materialized yet, use the completed sync job counters so a no-op retry
        does not make a healthy graph look empty.
        """
        result = await db.execute(
            select(
                SyncJob.entities_inserted,
                SyncJob.entities_updated,
                SyncJob.entities_deleted,
                SyncJob.entities_kept,
                SyncJob.entities_encountered,
            )
            .where(SyncJob.sync_id == sync_id)
            .where(SyncJob.status == SyncJobStatus.COMPLETED.value)
            .order_by(SyncJob.created_at.desc())
        )

        for row in result:
            encountered = row.entities_encountered if isinstance(row.entities_encountered, dict) else {}
            encountered_total = sum(
                int(value or 0) for value in encountered.values() if isinstance(value, (int, float))
            )
            observed_total = max(
                encountered_total,
                (row.entities_inserted or 0)
                + (row.entities_updated or 0)
                + (row.entities_kept or 0)
                - (row.entities_deleted or 0),
            )
            if observed_total > 0:
                return observed_total

        return 0

    async def _get_latest_sync_state_statistics(
        self,
        db: AsyncSession,
        *,
        sync_id: UUID,
        ctx: ApiContext,
    ) -> Dict[str, Any]:
        """Return the latest merged entity snapshot for an incremental sync.

        Incremental connector runs can emit only the cursor window for a table,
        while the sync state keeps the full merged view. Product summaries
        should display the merged view so dashboard, workbench, and graph pages
        do not swing between full and delta counts.
        """
        latest_state = await crud.sync_state.get_latest_by_sync_id(
            db,
            sync_id=sync_id,
            ctx=ctx,
        )
        if not latest_state:
            return {}
        state_data = latest_state.state_data
        if hasattr(state_data, "model_dump"):
            state_data = state_data.model_dump(mode="json")
        if not isinstance(state_data, Mapping):
            return {}
        statistics = state_data.get("statistics") or {}
        return dict(statistics) if isinstance(statistics, Mapping) else {}

    async def _build_source_summary(
        self,
        db: AsyncSession,
        source_connection: SourceConnection,
        ctx: ApiContext,
    ) -> schemas.ContextForgeSourceSummary:
        draft = await self._get_finalized_draft(db, source_connection, ctx)
        discovery = draft.discovery_snapshot if draft and draft.discovery_snapshot else {}
        objects = discovery.get("objects") or []
        source_identity = discovery.get("source_identity") or {}
        totals = discovery.get("totals") or {}
        sync_estimate = discovery.get("sync_estimate") or {}

        entity_states = await crud.source_connection.get_entity_states(
            db, source_connection, limit=100
        )
        entity_count = sum(state.get("total_count", 0) for state in entity_states)
        sync_state_statistics: Dict[str, Any] = {}
        if source_connection.sync_id:
            sync_state_statistics = await self._get_latest_sync_state_statistics(
                db,
                sync_id=source_connection.sync_id,
                ctx=ctx,
            )
            state_entity_count = int(sync_state_statistics.get("total_entities") or 0)
            if state_entity_count > entity_count:
                entity_count = state_entity_count
        if not entity_count and source_connection.sync_id:
            entity_count = await self._get_latest_job_entity_count(
                db,
                sync_id=source_connection.sync_id,
            )
        entity_types = [
            str(state.get("entity_type"))
            for state in entity_states
            if state.get("entity_type")
        ]
        graph_summary = await self._get_graph_summary(
            db,
            source_connection,
            entity_count,
            collection_readable_id=source_connection.readable_collection_id,
            organization_id=ctx.organization.id,
            entity_types=entity_types,
        )
        schedule_info = await crud.source_connection.get_schedule_info(db, source_connection)
        mapping_artifact = await self._get_latest_source_mapping(
            db,
            source_connection_id=source_connection.id,
            organization_id=ctx.organization.id,
        )
        generated_mapping = None
        if not mapping_artifact and discovery:
            generated_mapping = self.build_mapping_artifact_payload(
                provider=source_connection.short_name,
                source_name=source_connection.name,
                target_collection_id=source_connection.readable_collection_id,
                discovery_snapshot=discovery,
                status="preview",
                generated_by="summary_preview",
                drift_snapshot=(source_connection.config_fields or {}).get("drift"),
            )

        mappings = [
            schemas.ContextForgeMapping(
                object_name=str(item.get("name") or "object"),
                inferred_entity=str(item.get("inferred_entity") or "Entity"),
                rows=int(item.get("rows") or 0),
                columns=int(item.get("columns") or 0),
                foreign_keys=int(item.get("foreign_keys") or 0),
                pii=[str(value) for value in item.get("pii") or []],
                selected=bool(item.get("selected", True)),
            )
            for item in objects[:40]
        ]

        status = "active" if source_connection.is_authenticated else "pending_auth"
        if graph_summary.events_failed:
            status = "graph_attention"
        elif graph_summary.events_pending:
            status = "graph_pending"
        elif mapping_artifact and mapping_artifact.status in {"review_required", "stale"}:
            status = "forge_review"

        mapping_response = self._mapping_artifact_response(mapping_artifact) if mapping_artifact else None
        graph_preview = (
            mapping_response.graph_preview
            if mapping_response
            else (
                schemas.ContextForgeGraphPreview.model_validate(generated_mapping["graph_preview"])
                if generated_mapping
                else None
            )
        )

        return schemas.ContextForgeSourceSummary(
            source_connection_id=source_connection.id,
            source_name=source_connection.name,
            provider=source_connection.short_name,
            sync_id=source_connection.sync_id,
            status=status,
            cursor_field=(schedule_info or {}).get("cursor_field"),
            schedule=schedule_info,
            auth_summary=draft.auth_summary if draft else None,
            source_identity=source_identity,
            totals=totals,
            sync_estimate=sync_estimate,
            mappings=mappings,
            graph=graph_summary,
            forge_ready=bool((draft and draft.discovery_snapshot and mappings) or graph_preview),
            drift=(source_connection.config_fields or {}).get("drift") or {},
            mapping_artifact=mapping_response,
            graph_preview=graph_preview,
        )

    async def _get_finalized_draft(
        self,
        db: AsyncSession,
        source_connection: SourceConnection,
        ctx: ApiContext,
    ) -> SourceConnectionSetupDraft | None:
        result = await db.execute(
            select(SourceConnectionSetupDraft)
            .where(SourceConnectionSetupDraft.organization_id == ctx.organization.id)
            .where(
                SourceConnectionSetupDraft.finalized_source_connection_id
                == source_connection.id
            )
            .order_by(SourceConnectionSetupDraft.modified_at.desc())
            .limit(1)
        )
        return result.scalar_one_or_none()

    def build_mapping_artifact_payload(
        self,
        *,
        provider: str,
        source_name: str,
        target_collection_id: str | None,
        discovery_snapshot: Mapping[str, Any] | None,
        status: str,
        generated_by: str,
        catalog_snapshot: Iterable[Mapping[str, Any]] | None = None,
        drift_snapshot: Mapping[str, Any] | None = None,
    ) -> Dict[str, Any]:
        """Build a persisted Forge mapping payload from cached discovery/catalog data."""
        discovery_snapshot = discovery_snapshot or {}
        mapping_schema = self._build_mapping_schema(
            provider=provider,
            source_name=source_name,
            target_collection_id=target_collection_id,
            discovery_snapshot=discovery_snapshot,
            generated_by=generated_by,
            drift_snapshot=drift_snapshot,
        )
        schema_fingerprint = (
            fingerprint_catalog_snapshot(catalog_snapshot)
            if catalog_snapshot
            else fingerprint_discovery_snapshot(discovery_snapshot)
        )
        return {
            "mapping_schema": mapping_schema,
            "graph_preview": self._graph_preview_from_mapping_schema(
                mapping_schema=mapping_schema,
                provider=provider,
                source_name=source_name,
                status=status,
            ),
            "schema_fingerprint": schema_fingerprint,
        }

    async def _apply_ai_inference(
        self,
        payload: Dict[str, Any],
        *,
        provider: str,
        source_name: str,
        target_collection_id: str | None,
        status: str,
        ctx: ApiContext,
    ) -> Dict[str, Any]:
        """Run the ContextD ADK Forge agent and merge its proposals into the mapping."""
        mapping_schema = deepcopy(payload["mapping_schema"])
        agent_response = await run_context_forge_agent(
            organization_id=ctx.organization.id,
            collection_readable_id=target_collection_id,
            provider=provider,
            source_name=source_name,
            mapping_schema=mapping_schema,
        )
        if not agent_response:
            mapping_schema["ai_inference"] = {
                "status": "skipped",
                "agent": "contextd-adk",
                "reason": "disabled_or_unavailable",
                "checked_at": utc_now_naive().isoformat(),
            }
            payload["mapping_schema"] = mapping_schema
            payload["graph_preview"] = self._graph_preview_from_mapping_schema(
                mapping_schema=mapping_schema,
                provider=provider,
                source_name=source_name,
                status=status,
            )
            return payload

        mapping_schema = self._merge_agent_response(mapping_schema, agent_response)
        mapping_schema["ai_inference"] = {
            "status": "applied",
            "agent": "contextd-adk",
            "model_role": "schema_extraction",
            "checked_at": utc_now_naive().isoformat(),
            "proposals": {
                "entities": len(agent_response.entity_types),
                "relationships": len(agent_response.relationships),
                "facts": len(agent_response.fact_predicates),
                "warnings": len(agent_response.warnings),
            },
        }
        payload["mapping_schema"] = mapping_schema
        payload["graph_preview"] = self._graph_preview_from_mapping_schema(
            mapping_schema=mapping_schema,
            provider=provider,
            source_name=source_name,
            status=status,
        )
        return payload

    def _merge_agent_response(
        self,
        mapping_schema: Dict[str, Any],
        response: ForgeAgentResponse,
    ) -> Dict[str, Any]:
        entity_types = [
            dict(entity)
            for entity in mapping_schema.get("entity_types") or []
            if isinstance(entity, Mapping)
        ]
        entity_by_object = {
            self._lookup_key(str(entity.get("source_object") or "")): entity
            for entity in entity_types
            if entity.get("source_object")
        }

        for proposal in response.entity_types:
            entity = entity_by_object.get(self._lookup_key(proposal.source_object))
            if not entity or proposal.confidence < 0.55:
                continue
            if proposal.label:
                entity["label"] = self._humanize_identifier(proposal.label).replace(" ", "")
            if proposal.primary_key:
                entity["primary_keys"] = proposal.primary_key
            entity["ai"] = {
                "confidence": proposal.confidence,
                "rationale": proposal.rationale,
            }

        relationships = [
            dict(rel)
            for rel in mapping_schema.get("relationships") or []
            if isinstance(rel, Mapping)
        ]
        relationship_keys = {
            (
                str(rel.get("source")),
                str(rel.get("target")),
                str(rel.get("source_column") or ""),
                str(rel.get("label") or ""),
            )
            for rel in relationships
        }
        for proposal in response.relationships:
            if proposal.confidence < 0.58:
                continue
            source = entity_by_object.get(self._lookup_key(proposal.source_object))
            target = entity_by_object.get(self._lookup_key(proposal.target_object))
            if not source or not target or source.get("id") == target.get("id"):
                continue
            label = self._slug(proposal.label)
            key = (
                str(source.get("id")),
                str(target.get("id")),
                str(proposal.source_column or ""),
                label,
            )
            if key in relationship_keys:
                continue
            relationships.append(
                {
                    "id": self._slug(
                        f"ai_rel_{proposal.source_object}_{proposal.source_column or proposal.label}_{proposal.target_object}"
                    ),
                    "source": source["id"],
                    "target": target["id"],
                    "label": label,
                    "source_object": proposal.source_object,
                    "target_object": proposal.target_object,
                    "source_column": proposal.source_column,
                    "target_column": proposal.target_column,
                    "kind": proposal.kind or "ai_inferred",
                    "confidence": proposal.confidence,
                    "rationale": proposal.rationale,
                    "provenance": "contextd-adk",
                }
            )
            relationship_keys.add(key)

        facts = [
            dict(fact)
            for fact in mapping_schema.get("fact_predicates") or []
            if isinstance(fact, Mapping)
        ]
        fact_keys = {
            (
                str(fact.get("entity")),
                str(fact.get("source_column") or ""),
                str(fact.get("predicate") or ""),
            )
            for fact in facts
        }
        for proposal in response.fact_predicates:
            if proposal.confidence < 0.56:
                continue
            entity = entity_by_object.get(self._lookup_key(proposal.source_object))
            if not entity:
                continue
            predicate = self._slug(proposal.predicate)
            key = (str(entity["id"]), proposal.source_column, predicate)
            if key in fact_keys:
                continue
            facts.append(
                {
                    "id": self._slug(
                        f"ai_fact_{proposal.source_object}_{proposal.source_column}_{predicate}"
                    ),
                    "entity": entity["id"],
                    "predicate": predicate,
                    "label": proposal.label or self._humanize_identifier(proposal.source_column),
                    "source_object": proposal.source_object,
                    "source_column": proposal.source_column,
                    "kind": "ai_inferred_fact",
                    "confidence": proposal.confidence,
                    "rationale": proposal.rationale,
                    "provenance": "contextd-adk",
                }
            )
            fact_keys.add(key)

        warnings = [str(value) for value in mapping_schema.get("warnings") or []]
        for warning in response.warnings:
            warning_text = str(warning).strip()
            if warning_text and warning_text not in warnings:
                warnings.append(warning_text)

        mapping_schema["entity_types"] = entity_types
        mapping_schema["relationships"] = relationships[:48]
        mapping_schema["fact_predicates"] = facts[:24]
        mapping_schema["derived_facts"] = mapping_schema["fact_predicates"]
        mapping_schema["warnings"] = warnings[:12]
        return mapping_schema

    def _build_mapping_schema(
        self,
        *,
        provider: str,
        source_name: str,
        target_collection_id: str | None,
        discovery_snapshot: Mapping[str, Any],
        generated_by: str,
        drift_snapshot: Mapping[str, Any] | None,
    ) -> Dict[str, Any]:
        objects = [
            item
            for item in discovery_snapshot.get("objects") or []
            if isinstance(item, Mapping) and bool(item.get("selected", True))
        ][:40]
        source_identity = dict(discovery_snapshot.get("source_identity") or {})
        generated_at = utc_now_naive().isoformat()

        entity_types: list[dict[str, Any]] = []
        relationships: list[dict[str, Any]] = []
        fact_predicates: list[dict[str, Any]] = []
        warnings: list[str] = []
        table_to_entity: dict[str, str] = {}
        entity_to_object: dict[str, str] = {}
        entity_to_node_type: dict[str, str] = {}

        for item in objects:
            object_name = str(item.get("name") or "object")
            entity_label = self._entity_label(
                object_name,
                str(item.get("inferred_entity") or ""),
            )
            entity_id = self._slug(f"entity_{object_name}_{entity_label}")
            graph_node_type = self._graph_node_type_for_object(
                provider=provider,
                source_identity=source_identity,
                object_name=object_name,
            )
            fields = self._normalize_fields(item.get("fields") or [])
            primary_keys = [
                str(value)
                for value in (item.get("primary_keys") or [])
                if str(value).strip()
            ]
            if not primary_keys:
                primary_keys = [
                    field["name"] for field in fields if field.get("primary_key")
                ]
            properties = [
                field["name"]
                for field in fields
                if not field.get("primary_key") and not field.get("foreign_key")
            ][:12]
            badges: list[str] = []
            if item.get("pii"):
                badges.append("pii")
            if "fact" in str(item.get("inferred_entity") or "").lower():
                badges.append("fact")
            if "episode" in str(item.get("inferred_entity") or "").lower():
                badges.append("episode")
            if not primary_keys:
                badges.append("needs-key-review")

            entity_types.append(
                {
                    "id": entity_id,
                    "label": entity_label,
                    "graph_node_type": graph_node_type,
                    "source_object": object_name,
                    "object_type": item.get("type") or "table",
                    "selected": bool(item.get("selected", True)),
                    "rows": int(item.get("rows") or 0),
                    "columns": int(item.get("columns") or len(fields) or 0),
                    "foreign_keys": int(item.get("foreign_keys") or 0),
                    "primary_keys": primary_keys,
                    "properties": properties,
                    "pii": [str(value) for value in item.get("pii") or []],
                    "badges": badges,
                    "confidence": 0.86 if item.get("inferred_entity") else 0.72,
                }
            )
            entity_to_object[entity_id] = object_name
            entity_to_node_type[entity_id] = graph_node_type
            for key in self._table_lookup_keys(object_name, entity_label):
                table_to_entity[key] = entity_id

        for item in objects:
            source_object = str(item.get("name") or "object")
            source_entity = table_to_entity.get(self._lookup_key(source_object))
            if not source_entity:
                continue
            fields = self._normalize_fields(item.get("fields") or [])
            fk_details = list(item.get("foreign_key_details") or [])
            for field in fields:
                if field.get("foreign_key"):
                    fk_details.append(
                        {
                            "column": field["name"],
                            "ref_table": field.get("ref_table"),
                            "ref_column": field.get("ref_column"),
                        }
                    )
            seen_relationships: set[str] = set()
            for fk in fk_details:
                if not isinstance(fk, Mapping):
                    continue
                ref_table = str(fk.get("ref_table") or "").strip()
                column = str(fk.get("column") or fk.get("column_name") or "").strip()
                target_entity = self._entity_for_reference(
                    table_to_entity,
                    ref_table=ref_table,
                    column=column,
                )
                if not target_entity or target_entity == source_entity:
                    continue
                relationship_id = self._slug(
                    f"rel_{source_object}_{column or ref_table}_{target_entity}"
                )
                if relationship_id in seen_relationships:
                    continue
                seen_relationships.add(relationship_id)
                target_object = entity_to_object.get(target_entity)
                relationships.append(
                    {
                        "id": relationship_id,
                        "source": source_entity,
                        "target": target_entity,
                        "label": self._relationship_label(column, ref_table),
                        "edge_type": self._edge_type_for_reference(
                            ref_table or target_object or ""
                        ),
                        "direction": "bidirectional",
                        "source_object": source_object,
                        "target_object": target_object,
                        "source_column": column,
                        "target_column": str(fk.get("ref_column") or "id"),
                        "source_node_type": entity_to_node_type.get(source_entity),
                        "target_node_type": entity_to_node_type.get(target_entity),
                        "kind": "foreign_key",
                        "confidence": 0.92 if ref_table else 0.76,
                    }
                )

            if not fk_details and int(item.get("foreign_keys") or 0) > 0:
                warnings.append(
                    f"{source_object} reports foreign keys but detailed targets were not available."
                )

            for field in self._fact_candidate_fields(fields)[:2]:
                if len(fact_predicates) >= 12:
                    break
                predicate_id = self._slug(f"fact_{source_object}_{field['name']}")
                fact_predicates.append(
                    {
                        "id": predicate_id,
                        "entity": source_entity,
                        "predicate": f"has_{self._slug(field['name'])}",
                        "label": self._humanize_identifier(field["name"]),
                        "source_object": source_object,
                        "source_column": field["name"],
                        "data_type": field.get("data_type"),
                        "kind": "derived_fact",
                        "confidence": 0.74,
                    }
                )

        if objects and not relationships:
            warnings.append("No foreign-key relationships were discovered yet.")
        if drift_snapshot and (drift_snapshot.get("schema") or {}).get("changed"):
            warnings.append("Source schema drift is pending Forge review.")

        return {
            "version": 1,
            "provider": provider,
            "source_name": source_name,
            "target_collection_id": target_collection_id,
            "source_identity": source_identity,
            "generated_by": generated_by,
            "generated_at": generated_at,
            "entity_types": entity_types,
            "relationships": relationships[:32],
            "fact_predicates": fact_predicates,
            "derived_facts": fact_predicates,
            "episodes": [
                entity
                for entity in entity_types
                if "episode" in " ".join(entity.get("badges") or [])
            ],
            "warnings": warnings[:8],
        }

    def _graph_preview_from_mapping_schema(
        self,
        *,
        mapping_schema: Mapping[str, Any],
        provider: str,
        source_name: str,
        status: str,
    ) -> Dict[str, Any]:
        entities = [
            item
            for item in mapping_schema.get("entity_types") or []
            if isinstance(item, Mapping) and bool(item.get("selected", True))
        ][:10]
        facts = [
            item
            for item in mapping_schema.get("fact_predicates") or []
            if isinstance(item, Mapping)
        ][:8]
        relationships = [
            item
            for item in mapping_schema.get("relationships") or []
            if isinstance(item, Mapping)
        ][:32]

        nodes: list[dict[str, Any]] = [
            {
                "id": "source",
                "label": source_name,
                "kind": "source",
                "source_object": None,
                "status": status,
                "confidence": 1.0,
                "x": 50,
                "y": 8,
                "metrics": {"provider": provider},
                "properties": [],
                "badges": [provider],
            }
        ]
        entity_positions: dict[str, tuple[float, float]] = {}
        radius_x = 34
        radius_y = 25
        for index, entity in enumerate(entities):
            angle = (2 * math.pi * index / max(len(entities), 1)) - (math.pi / 2)
            x = 50 + radius_x * math.cos(angle)
            y = 50 + radius_y * math.sin(angle)
            entity_id = str(entity.get("id"))
            entity_positions[entity_id] = (x, y)
            nodes.append(
                {
                    "id": entity_id,
                    "label": str(entity.get("label") or entity_id),
                    "kind": "entity",
                    "source_object": entity.get("source_object"),
                    "status": status,
                    "confidence": float(entity.get("confidence") or 0.8),
                    "x": round(x, 2),
                    "y": round(y, 2),
                    "metrics": {
                        "rows": entity.get("rows") or 0,
                        "columns": entity.get("columns") or 0,
                    },
                    "properties": [str(value) for value in entity.get("properties") or []][:8],
                    "badges": [str(value) for value in entity.get("badges") or []][:4],
                }
            )

        edges: list[dict[str, Any]] = []
        edge_ids: set[str] = set()
        for entity in entities:
            entity_id = str(entity.get("id"))
            edge_id = self._slug(f"lineage_source_{entity_id}")
            edges.append(
                {
                    "id": edge_id,
                    "source": "source",
                    "target": entity_id,
                    "label": "extracts",
                    "kind": "lineage",
                    "status": status,
                    "confidence": 1.0,
                }
            )
            edge_ids.add(edge_id)

        for relationship in relationships:
            source_id = str(relationship.get("source") or "")
            target_id = str(relationship.get("target") or "")
            if source_id not in entity_positions or target_id not in entity_positions:
                continue
            edge_id = str(relationship.get("id") or self._slug(f"rel_{source_id}_{target_id}"))
            if edge_id in edge_ids:
                continue
            edges.append(
                {
                    "id": edge_id,
                    "source": source_id,
                    "target": target_id,
                    "label": str(relationship.get("label") or "relates"),
                    "kind": str(relationship.get("kind") or "relationship"),
                    "status": status,
                    "confidence": float(relationship.get("confidence") or 0.8),
                }
            )
            edge_ids.add(edge_id)

        for index, fact in enumerate(facts):
            parent_id = str(fact.get("entity") or "")
            if parent_id not in entity_positions:
                continue
            parent_x, parent_y = entity_positions[parent_id]
            offset = -9 if index % 2 else 9
            fact_id = str(fact.get("id") or self._slug(f"fact_{index}_{parent_id}"))
            nodes.append(
                {
                    "id": fact_id,
                    "label": str(fact.get("label") or fact.get("predicate") or "Fact"),
                    "kind": "fact",
                    "source_object": fact.get("source_object"),
                    "status": status,
                    "confidence": float(fact.get("confidence") or 0.72),
                    "x": round(max(8, min(92, parent_x + offset)), 2),
                    "y": round(max(16, min(88, parent_y + 13)), 2),
                    "metrics": {"column": fact.get("source_column")},
                    "properties": [str(fact.get("source_column") or "")],
                    "badges": ["derived"],
                }
            )
            edge_id = self._slug(f"fact_edge_{parent_id}_{fact_id}")
            edges.append(
                {
                    "id": edge_id,
                    "source": parent_id,
                    "target": fact_id,
                    "label": str(fact.get("predicate") or "has_fact"),
                    "kind": "fact",
                    "status": status,
                    "confidence": float(fact.get("confidence") or 0.72),
                }
            )

        return {
            "status": status,
            "provider": provider,
            "source_name": source_name,
            "generated_at": utc_now_naive().isoformat(),
            "nodes": nodes[:22],
            "edges": edges[:48],
            "summary": {
                "entity_types": len(entities),
                "relationships": len(relationships),
                "facts": len(facts),
                "warnings": len(mapping_schema.get("warnings") or []),
            },
            "warnings": [str(value) for value in mapping_schema.get("warnings") or []][:8],
        }

