    def _normalize_fields(self, fields: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
        normalized: list[dict[str, Any]] = []
        for field in fields:
            if not isinstance(field, Mapping):
                continue
            name = str(field.get("name") or field.get("column_name") or "").strip()
            if not name:
                continue
            normalized.append(
                {
                    "name": name,
                    "data_type": field.get("data_type") or field.get("udt_name"),
                    "nullable": bool(field.get("nullable", field.get("is_nullable", True))),
                    "primary_key": bool(
                        field.get("primary_key", field.get("is_primary_key", False))
                    ),
                    "foreign_key": bool(
                        field.get("foreign_key", field.get("is_foreign_key", False))
                    ),
                    "ref_schema": field.get("ref_schema"),
                    "ref_table": field.get("ref_table"),
                    "ref_column": field.get("ref_column"),
                }
            )
        return normalized

    def _entity_label(self, object_name: str, inferred_entity: str) -> str:
        raw = (inferred_entity or "").split("·")[0].split("→")[0].strip()
        object_label = self._humanize_identifier(object_name.split(".")[-1]).replace(" ", "")
        if raw and "review" not in raw.lower() and "junction" not in raw.lower():
            raw_label = self._humanize_identifier(raw).replace(" ", "")
            if (
                object_label
                and raw_label
                and object_label.lower().startswith(raw_label.lower())
                and len(object_label) - len(raw_label) <= 2
            ):
                return object_label
            return raw_label
        return object_label

    def _relationship_label(self, column: str, ref_table: str) -> str:
        if column:
            label = re.sub(r"(_id|_uuid|_key)$", "", column.lower())
            return self._slug(label) or "references"
        if ref_table:
            return f"references_{self._slug(ref_table.split('.')[-1])}"
        return "references"

    def _edge_type_for_reference(self, ref_table: str) -> str:
        if ref_table:
            return f"RELATES_TO_{self._slug(ref_table.split('.')[-1]).upper()}"
        return "RELATED_TO"

    def _entity_for_reference(
        self,
        table_to_entity: Mapping[str, str],
        *,
        ref_table: str,
        column: str,
    ) -> str | None:
        candidates = []
        if ref_table:
            candidates.extend(self._table_lookup_keys(ref_table, ""))
        if column:
            base = re.sub(r"(_id|_uuid|_key)$", "", column.lower())
            bases = [base]
            if "_" in base:
                # home_studio_id should resolve to studios, not home_studios.
                bases.append(base.rsplit("_", 1)[-1])
            for item in bases:
                candidates.extend([item, *self._plural_candidates(item), self._singular(item)])
        for candidate in candidates:
            match = table_to_entity.get(self._lookup_key(candidate))
            if match:
                return match
        return None

    def _table_lookup_keys(self, object_name: str, entity_label: str) -> list[str]:
        name = object_name.split(".")[-1]
        keys = {name, self._singular(name), entity_label, self._singular(entity_label)}
        for alias in self._object_aliases(name):
            keys.add(alias)
            keys.add(self._singular(alias))
        return [self._lookup_key(key) for key in keys if key]

    def _lookup_key(self, value: str) -> str:
        return self._slug(value).lower()

    def _object_aliases(self, name: str) -> set[str]:
        normalized = self._slug(name).lower()
        aliases = {normalized}
        for prefix in ("public_", "vw_", "dim_", "fct_", "stg_", "brdg_"):
            if normalized.startswith(prefix):
                aliases.add(normalized[len(prefix) :])
        return aliases

    def _plural_candidates(self, value: str) -> list[str]:
        base = self._slug(value).lower()
        candidates = [f"{base}s", f"{base}es"]
        if base.endswith("y"):
            candidates.append(f"{base[:-1]}ies")
        if base.endswith("s"):
            candidates.append(base)
        return candidates

    def _graph_node_type_for_object(
        self,
        *,
        provider: str,
        source_identity: Mapping[str, Any],
        object_name: str,
    ) -> str:
        object_slug = self._slug(object_name.split(".")[-1])
        if provider == "clickhouse":
            database = str(
                source_identity.get("Database")
                or source_identity.get("database")
                or source_identity.get("db")
                or ""
            ).strip()
            if database:
                return f"DatabaseTableNode_{database}_{object_slug}"
        schema = str(
            source_identity.get("Schema")
            or source_identity.get("schema")
            or source_identity.get("db_schema")
            or ""
        ).strip()
        if schema and "." not in object_name:
            return f"DatabaseTableNode_{schema}_{object_slug}"
        if "." in object_name:
            schema_name, table_name = object_name.split(".", 1)
            return f"DatabaseTableNode_{self._slug(schema_name)}_{self._slug(table_name)}"
        return f"DatabaseTableNode_{object_slug}"

    def _slug(self, value: str) -> str:
        slug = re.sub(r"[^a-zA-Z0-9]+", "_", str(value)).strip("_").lower()
        return slug or "item"

    def _humanize_identifier(self, value: str) -> str:
        value = re.sub(r"^(dim|fct|fact|stg|brdg|bridge)_", "", str(value), flags=re.I)
        value = value.replace(".", "_")
        words = [word for word in re.split(r"[_\s-]+", value) if word]
        if not words:
            return "Entity"
        words[-1] = self._singular(words[-1])
        return " ".join(word[:1].upper() + word[1:] for word in words)

    def _singular(self, value: str) -> str:
        value = str(value)
        lowered = value.lower()
        irregular = {
            "people": "person",
            "children": "child",
            "men": "man",
            "women": "woman",
        }
        if lowered in irregular:
            replacement = irregular[lowered]
            return replacement[:1].upper() + replacement[1:] if value[:1].isupper() else replacement
        if lowered in {"news", "series", "species"}:
            return value
        if len(value) > 3 and lowered.endswith("ies"):
            return f"{value[:-3]}y"
        if len(value) > 4 and lowered.endswith(("sses", "ches", "shes", "xes", "zes")):
            return value[:-2]
        if len(value) > 3 and lowered.endswith("ses"):
            return value[:-2]
        if len(value) > 2 and lowered.endswith("s") and not lowered.endswith(
            ("ss", "us", "is")
        ):
            return value[:-1]
        return value

    def _fact_candidate_fields(self, fields: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
        priority = ("amount", "total", "status", "email", "score", "count", "date", "time")
        candidates: list[dict[str, Any]] = []
        for field in fields:
            name = str(field.get("name") or "")
            if field.get("primary_key") or field.get("foreign_key"):
                continue
            lowered = name.lower()
            if any(token in lowered for token in priority):
                candidates.append(dict(field))
        if candidates:
            return candidates
        return [
            dict(field)
            for field in fields
            if not field.get("primary_key") and not field.get("foreign_key")
        ][:2]

    def _pii_from_fields(self, fields: Iterable[Mapping[str, Any]]) -> list[str]:
        labels: set[str] = set()
        for field in fields:
            for label in field.get("pii") or []:
                if label:
                    labels.add(str(label))
            name = str(field.get("name") or "").lower()
            if "email" in name:
                labels.add("email")
            if "phone" in name:
                labels.add("phone")
            if "name" in name:
                labels.add("name")
            if "address" in name:
                labels.add("address")
            if "token" in name or "secret" in name:
                labels.add("secret")
        return sorted(labels)

    async def _get_graph_summary(
        self,
        db: AsyncSession,
        source_connection: SourceConnection,
        entity_count: int,
        *,
        collection_readable_id: str,
        organization_id: UUID,
        entity_types: List[str],
    ) -> schemas.ContextForgeGraphSummary:
        neo4j_counts = await self._get_neo4j_counts(
            collection_readable_id=collection_readable_id,
            organization_id=organization_id,
            entity_types=entity_types,
        )

        if not source_connection.sync_id:
            return schemas.ContextForgeGraphSummary(
                entity_count=entity_count,
                neo4j_nodes=neo4j_counts["nodes"],
                neo4j_edges=neo4j_counts["edges"],
            )

        latest_job_result = await db.execute(
            select(SyncJob.id, SyncJob.status)
            .where(SyncJob.sync_id == source_connection.sync_id)
            .order_by(SyncJob.created_at.desc())
            .limit(1)
        )
        latest_job = latest_job_result.one_or_none()

        result = []
        if latest_job:
            result = (
                await db.execute(
                    select(
                        GraphEvent.event_type,
                        GraphEvent.commit_status,
                        func.count(GraphEvent.id).label("count"),
                    )
                    .where(GraphEvent.sync_job_id == latest_job.id)
                    .group_by(GraphEvent.event_type, GraphEvent.commit_status)
                )
            ).all()

        by_status: Dict[str, int] = defaultdict(int)
        event_nodes_committed = 0
        event_edges_committed = 0
        total = 0
        for row in result:
            count = row.count or 0
            total += count
            by_status[row.commit_status] += count
            if row.commit_status == "committed" and row.event_type == "NODE_CREATE":
                event_nodes_committed += count
            if row.commit_status == "committed" and row.event_type == "EDGE_CREATE":
                event_edges_committed += count

        return schemas.ContextForgeGraphSummary(
            entity_count=entity_count,
            graph_events_total=total,
            nodes_committed=neo4j_counts["nodes"] or event_nodes_committed,
            edges_committed=neo4j_counts["edges"] or event_edges_committed,
            neo4j_nodes=neo4j_counts["nodes"],
            neo4j_edges=neo4j_counts["edges"],
            events_pending=by_status["pending"],
            events_failed=by_status["failed"],
            events_skipped=by_status["skipped"],
        )

    async def _get_unique_committed_graph_counts(
        self,
        db: AsyncSession,
        *,
        sync_id: UUID,
        organization_id: UUID,
    ) -> Dict[str, int]:
        """Count the distinct graph objects represented by committed events."""
        node_result = await db.execute(
            select(func.count(func.distinct(GraphEvent.node_id)))
            .where(GraphEvent.sync_id == sync_id)
            .where(GraphEvent.organization_id == organization_id)
            .where(GraphEvent.commit_status == "committed")
            .where(GraphEvent.event_type.like("NODE%"))
            .where(GraphEvent.node_id.is_not(None))
        )
        edge_result = await db.execute(
            text("""
                SELECT COUNT(*) AS edges
                FROM (
                    SELECT DISTINCT
                        event_data->'payload'->'from_node'->>'node_id' AS source_node_id,
                        event_data->'payload'->'to_node'->>'node_id' AS target_node_id,
                        event_data->'payload'->>'edge_type' AS edge_type
                    FROM graph_events
                    WHERE sync_id = :sync_id
                      AND organization_id = :organization_id
                      AND commit_status = 'committed'
                      AND event_type LIKE 'EDGE%'
                ) AS distinct_edges
            """),
            {
                "sync_id": str(sync_id),
                "organization_id": str(organization_id),
            },
        )
        edge_row = edge_result.one_or_none()
        return {
            "nodes": int(node_result.scalar_one() or 0),
            "edges": int((edge_row._mapping["edges"] if edge_row else 0) or 0),
        }

    async def _get_neo4j_counts(
        self,
        *,
        collection_readable_id: str,
        organization_id: UUID,
        entity_types: List[str],
    ) -> Dict[str, int]:
        """Return actual persisted Neo4j counts for this collection/source slice."""
        try:
            from contextd.platform.graph.factory import get_graph_driver

            driver = await get_graph_driver()
            target_database = await driver.ensure_context_database(
                organization_id,
                collection_readable_id,
            )
            params = {
                "organization_id": str(organization_id),
                "collection_id": collection_readable_id,
            }
            node_rows = await driver.execute_read(
                """
                MATCH (n:GraphNode {organization_id: $organization_id})
                WHERE n.collection_id = $collection_id
                RETURN count(n) AS nodes
                """,
                params,
                database=target_database,
            )
            edge_rows = await driver.execute_read(
                """
                MATCH (source:GraphNode {organization_id: $organization_id})
                      -[r:RELATES_TO]->
                      (target:GraphNode {organization_id: $organization_id})
                WHERE source.collection_id = $collection_id
                  AND target.collection_id = $collection_id
                  AND r.collection_id = $collection_id
                WITH CASE
                       WHEN source.node_id < target.node_id
                       THEN source.node_id + '|' + coalesce(properties(r)['relationship_type'], type(r)) + '|' + target.node_id
                       ELSE target.node_id + '|' + coalesce(properties(r)['relationship_type'], type(r)) + '|' + source.node_id
                     END AS logical_edge
                RETURN count(DISTINCT logical_edge) AS edges
                """,
                params,
                database=target_database,
            )
            return {
                "nodes": int((node_rows[0] if node_rows else {}).get("nodes") or 0),
                "edges": int((edge_rows[0] if edge_rows else {}).get("edges") or 0),
            }
        except Exception as exc:
            logger.warning(
                "Unable to fetch Neo4j Context Forge counts for %s: %s",
                collection_readable_id,
                exc,
            )
            return {"nodes": 0, "edges": 0}

    def _build_pipeline(self, totals: Dict[str, Any]) -> List[schemas.ContextForgePipelineStep]:
        entities = int(totals.get("entities") or 0)
        committed = int(totals.get("neo4j_nodes") or totals.get("nodes_committed") or 0)
        edges = int(totals.get("neo4j_edges") or totals.get("edges_committed") or 0)
        pending = int(totals.get("pending_events") or 0)
        failed = int(totals.get("failed_events") or 0)

        graph_status = "done" if committed > 0 and failed == 0 and pending == 0 else "pending"
        if failed:
            graph_status = "failed"
        elif pending:
            graph_status = "running"

        return [
            schemas.ContextForgePipelineStep(
                key="extract",
                label="Extract source records",
                status="done" if entities else "not_started",
                detail=f"{entities:,} entities",
            ),
            schemas.ContextForgePipelineStep(
                key="normalize",
                label="Normalize entities",
                status="done" if entities else "not_started",
                detail="typed rows grouped by source object" if entities else "waiting for sync",
            ),
            schemas.ContextForgePipelineStep(
                key="graph_events",
                label="Emit graph events",
                status="done" if int(totals.get("graph_events") or 0) else "not_started",
                detail=f"{int(totals.get('graph_events') or 0):,} events",
            ),
            schemas.ContextForgePipelineStep(
                key="neo4j_commit",
                label="Commit to ContextD graph",
                status=graph_status,
                detail=f"{committed:,} nodes · {edges:,} edges",
            ),
            schemas.ContextForgePipelineStep(
                key="forge_preview",
                label="Context Forge preview",
                status="ready" if int(totals.get("forge_ready_sources") or 0) else "pending",
                detail=f"{int(totals.get('forge_ready_sources') or 0)} source mappings",
            ),
        ]


